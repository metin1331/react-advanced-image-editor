/**
 * Cross-platform emoji sticker rendering via Twemoji PNGs.
 *
 * Native `fillText(emoji)` looks different on Windows / iOS / Android and can
 * fail to color-render in some canvas environments. Twemoji bitmaps keep the
 * preview and export visually consistent.
 */

import type { MarkupState } from './types';

/** Pinned Twemoji release — change deliberately; URLs must stay cacheable. */
const TWEMOJI_VERSION = '15.1.0';
const TWEMOJI_PNG = `https://cdn.jsdelivr.net/gh/jdecked/twemoji@${TWEMOJI_VERSION}/assets/72x72`;

const EMOJI_FONT =
  '"Apple Color Emoji","Segoe UI Emoji","Noto Color Emoji","Android Emoji","EmojiOne Color",sans-serif';

const imageCache = new Map<string, HTMLImageElement | null>();
const pending = new Map<string, Promise<HTMLImageElement | null>>();

/** Convert an emoji (incl. ZWJ sequences) to a Twemoji file stem. */
export function emojiToTwemojiCode(emoji: string): string {
  const cps: number[] = [];
  for (const ch of emoji) {
    const cp = ch.codePointAt(0);
    if (cp == null) continue;
    // Skip variation selector-16; Twemoji filenames omit it.
    if (cp === 0xfe0f) continue;
    cps.push(cp);
  }
  return cps.map((c) => c.toString(16)).join('-');
}

export function twemojiPngUrl(emoji: string): string {
  return `${TWEMOJI_PNG}/${emojiToTwemojiCode(emoji)}.png`;
}

function loadTwemojiImage(emoji: string): Promise<HTMLImageElement | null> {
  if (typeof Image === 'undefined') return Promise.resolve(null);
  const cached = imageCache.get(emoji);
  if (cached !== undefined) return Promise.resolve(cached);
  const inflight = pending.get(emoji);
  if (inflight) return inflight;

  const promise = new Promise<HTMLImageElement | null>((resolve) => {
    const img = new Image();
    img.crossOrigin = 'anonymous';
    img.decoding = 'async';
    img.onload = () => {
      imageCache.set(emoji, img);
      pending.delete(emoji);
      resolve(img);
    };
    img.onerror = () => {
      imageCache.set(emoji, null);
      pending.delete(emoji);
      resolve(null);
    };
    img.src = twemojiPngUrl(emoji);
  });
  pending.set(emoji, promise);
  return promise;
}

/** Warm the Twemoji cache for a single emoji (fire-and-forget OK). */
export function preloadStickerEmoji(emoji: string): Promise<HTMLImageElement | null> {
  return loadTwemojiImage(emoji);
}

/** Ensure every sticker in markup has a cached bitmap before export. */
export async function preloadMarkupStickers(markup?: MarkupState | null): Promise<void> {
  if (!markup?.objects?.length) return;
  const emojis = [
    ...new Set(
      markup.objects.filter((o) => o.kind === 'sticker').map((o) => (o as { emoji: string }).emoji)
    ),
  ];
  await Promise.all(emojis.map((e) => loadTwemojiImage(e)));
}

export function getCachedStickerImage(emoji: string): HTMLImageElement | null | undefined {
  return imageCache.get(emoji);
}

/** Draw emoji into a pixel box — Twemoji when ready, system emoji otherwise. */
export function paintStickerEmoji(
  ctx: CanvasRenderingContext2D,
  emoji: string,
  x: number,
  y: number,
  w: number,
  h: number
) {
  if (!emoji || w <= 0 || h <= 0) return;
  const img = imageCache.get(emoji);
  if (img) {
    ctx.drawImage(img, x, y, w, h);
    return;
  }
  // Kick off load for next paint; first frame uses system glyph.
  void loadTwemojiImage(emoji);
  const size = Math.max(1, Math.min(w, h));
  ctx.save();
  ctx.font = `${size * 0.92}px ${EMOJI_FONT}`;
  ctx.textAlign = 'center';
  ctx.textBaseline = 'middle';
  ctx.fillText(emoji, x + w / 2, y + h / 2 + size * 0.04);
  ctx.restore();
}

